
from datetime import datetime, timezone
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field


BASE_DIR = Path(__file__).resolve().parent.parent
MODEL_PATH = BASE_DIR / "models" / "pawlink_svm_model.joblib"

FEATURE_NAMES = [
    "head_injury",
    "head_injury_severity",
    "breathing_difficulty",
    "consciousness",
    "bleeding_severity",
    "mobility_status",
    "suspected_fracture",
    "seizures",
    "suspected_poisoning",
    "trapped",
    "roadside_danger",
    "orange_warning_symptoms",
]

MODEL_VERSION = "pawlink-svm-1.0"


class RescuePriorityRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    head_injury: Literal["No", "Yes"]
    head_injury_severity: Literal[
        "Minor", "Moderate", "Not applicable", "Severe"
    ]
    breathing_difficulty: Literal[
        "Difficulty", "Normal", "Severe difficulty", "Unknown"
    ]
    consciousness: Literal[
        "Alert", "Unconscious", "Unknown", "Weak/disoriented"
    ]
    bleeding_severity: Literal[
        "Heavy/uncontrolled", "Minor", "Moderate", "None", "Unknown"
    ]
    mobility_status: Literal[
        "Limping/limited", "Normal", "Unable to stand", "Unknown"
    ]
    suspected_fracture: Literal["No", "Suspected", "Unknown"]
    seizures: Literal["No", "Unknown", "Yes"]
    suspected_poisoning: Literal["No", "Suspected", "Unknown"]
    trapped: Literal["No", "Yes"]
    roadside_danger: Literal["No", "Yes"]
    orange_warning_symptoms: Literal[
        "",
        "Blood in urine, stool or vomit",
        "Drooping wing, cannot stay on the perch",
        "Droppings changed: liquid, bloody, unusual color",
        "Eye: injury, kept shut or clouded",
        "Lameness: not bearing weight on a limb at all",
        "Lethargy: hiding, not itself",
        "Not eating for over a day",
        "Not eating longer than usual and visibly losing weight",
        "Pain: whining, crying out, won't let you touch",
        "Temperature above 39.5 °C",
        "Vomiting or diarrhea several times a day",
    ]


app = FastAPI(
    title="PawLink AI ML Service",
    description="AI-powered rescue priority classification service for PawLink AI.",
    version="1.0.0",
)

model = None
model_load_error = None

try:
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(f"Model file not found: {MODEL_PATH}")

    model = joblib.load(MODEL_PATH)

    actual_features = list(model.feature_names_in_)
    if actual_features != FEATURE_NAMES:
        raise ValueError(
            "Model feature names do not match the API feature schema."
        )

except Exception as exc:
    model_load_error = str(exc)


@app.get("/")
def root():
    return {
        "success": True,
        "message": "Welcome to PawLink AI ML Service",
        "service": "PawLink AI",
        "version": "1.0.0",
    }


@app.get("/health")
def health_check():
    return {
        "success": model is not None,
        "status": "healthy" if model is not None else "model_unavailable",
        "service": "pawlink-ml-service",
        "model_loaded": model is not None,
        "model_version": MODEL_VERSION if model is not None else None,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }


@app.post("/predict/rescue-priority")
def predict_rescue_priority(request: RescuePriorityRequest):
    if model is None:
        raise HTTPException(
            status_code=503,
            detail=f"Rescue priority model unavailable: {model_load_error}",
        )

    try:
        features = pd.DataFrame(
            [request.model_dump()],
            columns=FEATURE_NAMES,
        )

        priority = str(model.predict(features)[0])

        return {
            "success": True,
            "status": "PREDICTION_COMPLETED",
            "message": "Prediction generated by the saved PawLink SVM model.",
            "data": {
                "model_version": MODEL_VERSION,
                "model_name": "SVM",
                "priority": priority,
                "confidence": None,
                "confidence_note": (
                    "Probability-based confidence is not configured."
                ),
                "vision": None,
                "available_classes": [str(c) for c in model.classes_],
            },
            "received_features": request.model_dump(),
        }

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Rescue priority prediction failed: {exc}",
        ) from exc
